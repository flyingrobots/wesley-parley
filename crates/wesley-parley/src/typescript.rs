//! Parley's message types in TypeScript (flyingrobots/parley#120), rendered from the
//! [`model`](crate::model) through wesley-typescript's swc syntax tree.
//!
//! - One interface per message and per object a message reaches; an optional field is `field?: T`
//!   (absent when unset, never null); `event` and every other literal field is a literal type.
//! - `_schema` is the literal `{ id; version }` of its own message.
//! - A GraphQL enum is a string-literal union alias; an inline `@parley_enum` is an inline union.
//! - `Line` is the union of every message, discriminated by `event`.
//!
//! Objects are open in Parley, and TypeScript interfaces are structurally open already, so no
//! index signature is added: an object literal with a misspelled field is still caught.

use std::collections::BTreeMap;

use wesley_typescript_syntax::{print_module, Declaration, Module, Property, TsType};

use crate::model::{Catalog, Object, Value};
use crate::Error;

/// Renders the module.
///
/// # Errors
///
/// [`Error::Render`] when the syntax library refuses a declaration (for example a name that is
/// not a TypeScript identifier).
pub fn render(catalog: &Catalog) -> Result<String, Error> {
    let mut declarations = Vec::new();

    // Enum aliases first, in name order.
    let mut enums: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for o in catalog.objects.values() {
        for f in &o.fields {
            collect_enums(&f.value, &mut enums);
        }
    }
    for (name, values) in enums {
        declarations.push(Declaration::TypeAlias {
            name,
            doc: None,
            ty: union_of_strings(&values),
        });
    }

    let message_objects: Vec<&str> = catalog.messages.iter().map(|m| m.object.as_str()).collect();
    let refs: Vec<&str> = catalog
        .objects
        .values()
        .flat_map(|o| o.fields.iter())
        .filter_map(|f| match &f.value {
            Value::MessageRef { object, .. } => Some(object.as_str()),
            _ => None,
        })
        .collect();
    for o in catalog.objects.values() {
        if message_objects.contains(&o.name.as_str()) || refs.contains(&o.name.as_str()) {
            continue;
        }
        declarations.push(interface(catalog, o, None));
    }
    for m in &catalog.messages {
        let o = &catalog.objects[&m.object];
        let mut doc = o.description.clone().unwrap_or_default();
        if !doc.is_empty() {
            doc.push_str("\n\n");
        }
        doc.push_str(&format!(
            "Message `{}`, schema version `{}`.",
            m.id, m.version
        ));
        declarations.push(interface(catalog, o, Some(doc)));
    }
    declarations.push(Declaration::TypeAlias {
        name: "Line".to_string(),
        doc: Some("Any Parley message, told apart by `event`.".to_string()),
        ty: TsType::Union(
            catalog
                .messages
                .iter()
                .map(|m| TsType::Ref(m.object.clone()))
                .collect(),
        ),
    });

    print_module(&Module {
        doc: Some(
            "Parley's message types, generated by wesley-parley from Parley's SDL. Do not edit."
                .to_string(),
        ),
        declarations,
    })
    .map_err(|e| Error::Render(e.to_string()))
}

fn collect_enums(v: &Value, out: &mut BTreeMap<String, Vec<String>>) {
    match v {
        Value::StringEnum {
            values,
            type_name: Some(name),
        } => {
            out.insert(name.clone(), values.clone());
        }
        Value::List { item, .. } => collect_enums(item, out),
        _ => {}
    }
}

fn union_of_strings(values: &[String]) -> TsType {
    TsType::Union(
        values
            .iter()
            .map(|v| TsType::StringLiteral(v.clone()))
            .collect(),
    )
}

fn interface(catalog: &Catalog, o: &Object, doc: Option<String>) -> Declaration {
    Declaration::Interface {
        name: o.name.clone(),
        doc,
        properties: o
            .fields
            .iter()
            .map(|f| Property {
                name: f.name.clone(),
                optional: !f.required,
                readonly: false,
                ty: ts_type(catalog, &f.value),
                doc: f.description.clone(),
            })
            .collect(),
    }
}

fn ts_type(catalog: &Catalog, v: &Value) -> TsType {
    match v {
        Value::String(_) => TsType::String,
        Value::Integer { .. } => TsType::Number,
        Value::Boolean => TsType::Boolean,
        Value::Any => TsType::Unknown,
        Value::JsonObject { .. } => TsType::Record(Box::new(TsType::Unknown)),
        Value::Const { value } => match value {
            serde_json::Value::String(s) => TsType::StringLiteral(s.clone()),
            serde_json::Value::Bool(b) => TsType::BooleanLiteral(*b),
            serde_json::Value::Number(n) => {
                n.as_i64().map_or(TsType::Number, TsType::NumberLiteral)
            }
            _ => TsType::Unknown,
        },
        Value::StringEnum { values, type_name } => match type_name {
            Some(name) => TsType::Ref(name.clone()),
            None => union_of_strings(values),
        },
        Value::MessageRef {
            object,
            id,
            version,
        } => {
            let fields = &catalog.objects[object].fields;
            let doc = |name: &str| {
                fields
                    .iter()
                    .find(|f| f.name == name)
                    .and_then(|f| f.description.clone())
            };
            TsType::Object(vec![
                Property {
                    name: "id".into(),
                    optional: false,
                    readonly: false,
                    ty: TsType::StringLiteral(id.clone()),
                    doc: doc("id"),
                },
                Property {
                    name: "version".into(),
                    optional: false,
                    readonly: false,
                    ty: TsType::StringLiteral(version.clone()),
                    doc: doc("version"),
                },
            ])
        }
        Value::Object { name, .. } => TsType::Ref(name.clone()),
        Value::List { item, .. } => TsType::Array(Box::new(ts_type(catalog, item))),
    }
}

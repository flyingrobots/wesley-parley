//! Parley's message types in Rust (flyingrobots/parley#123), rendered from the
//! [`model`](crate::model) as a `syn` tree and printed through wesley-rust's `prettyplease`
//! printer.
//!
//! - One struct per message and per object a message reaches, deriving serde's traits. An optional
//!   field is `Option<T>`, absent when `None` and never serialised as `null`.
//! - An open object keeps the fields it does not name in a flattened `extra` map, so a reader or a
//!   transforming writer never drops a tool's own fields; a closed object refuses unknown fields.
//! - Every integer is `i64`; any JSON value is `serde_json::Value`; a GraphQL enum and an inline
//!   `@parley_enum` are Rust enums whose variants rename to the wire strings.
//! - Each message has `SCHEMA_ID` and `SCHEMA_VERSION` constants.
//!
//! Standard and serde paths are fully qualified, so a Parley type named like one cannot shadow it.

use std::collections::BTreeMap;

use proc_macro2::{Span, TokenStream};
use quote::quote;
use syn::{parse_quote, Item, LitStr};
use wesley_rust_syntax::{doc_attrs, ident, inner_doc_attrs, naming, print_file, unique_names};

use crate::model::{Catalog, Field, Object, Value};
use crate::Error;

/// Renders the module.
///
/// # Errors
///
/// [`Error::Render`] when two enum names collide.
pub fn render(catalog: &Catalog) -> Result<String, Error> {
    let enums = enum_names(catalog)?;
    let mut items: Vec<Item> = Vec::new();

    let mut declared: Vec<(&String, &Vec<String>)> = enums
        .iter()
        .map(|(name, (values, _))| (name, values))
        .collect();
    declared.sort();
    for (name, values) in declared {
        items.push(enum_item(name, values));
    }
    for o in catalog.objects.values() {
        items.push(struct_item(o, &enums));
    }
    for m in &catalog.messages {
        let name = ident(&naming::type_name(&m.object));
        let id = LitStr::new(&m.id, Span::call_site());
        let version = LitStr::new(&m.version, Span::call_site());
        items.push(parse_quote! {
            impl #name {
                /// The message id this type carries in `_schema.id`.
                pub const SCHEMA_ID: &'static str = #id;
                /// The schema version this type carries in `_schema.version`.
                pub const SCHEMA_VERSION: &'static str = #version;
            }
        });
    }

    // An optional field holding any JSON value tells a present `null` from an absent field.
    let keeps_null = catalog
        .objects
        .values()
        .flat_map(|o| o.fields.iter())
        .any(keeps_present_null);
    if keeps_null {
        items.push(parse_quote! {
            /// Deserialises a present value, `null` included, as `Some`; an absent field stays `None`.
            fn deserialize_present<'de, D: ::serde::Deserializer<'de>>(
                deserializer: D,
            ) -> ::core::result::Result<::core::option::Option<::serde_json::Value>, D::Error> {
                <::serde_json::Value as ::serde::Deserialize>::deserialize(deserializer).map(::core::option::Option::Some)
            }
        });
    }

    let file = syn::File {
        shebang: None,
        attrs: inner_doc_attrs(
            "Parley's message types, generated by wesley-parley from Parley's SDL. Do not edit.",
        ),
        items,
    };
    Ok(print_file(&file))
}

/// Every enum the module declares, by Rust name: a GraphQL enum by its type name, an inline
/// `@parley_enum` as `<Object><Field>`. The key of the inner map is where it is used.
type Enums = BTreeMap<String, (Vec<String>, Vec<(String, String)>)>;

fn enum_names(catalog: &Catalog) -> Result<Enums, Error> {
    let mut out: Enums = BTreeMap::new();
    for o in catalog.objects.values() {
        for f in &o.fields {
            let mut v = &f.value;
            while let Value::List { item, .. } = v {
                v = item;
            }
            if let Value::StringEnum { values, type_name } = v {
                let name = type_name.as_ref().map_or_else(
                    || naming::type_name(&format!("{}_{}", o.name, f.name)),
                    |t| naming::type_name(t),
                );
                let entry = out
                    .entry(name.clone())
                    .or_insert_with(|| (values.clone(), Vec::new()));
                if &entry.0 != values {
                    return Err(Error::Render(format!(
                        "two enums would both be named {name} with different values"
                    )));
                }
                entry.1.push((o.name.clone(), f.name.clone()));
            }
        }
    }
    Ok(out)
}

fn enum_item(name: &str, values: &[String]) -> Item {
    let name = ident(name);
    let variants = unique_names(values, naming::variant_name);
    let arms = values.iter().zip(&variants).map(|(wire, variant)| {
        let variant = ident(variant);
        let wire = LitStr::new(wire, Span::call_site());
        quote! {
            #[serde(rename = #wire)]
            #variant,
        }
    });
    parse_quote! {
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, ::serde::Serialize, ::serde::Deserialize)]
        pub enum #name {
            #(#arms)*
        }
    }
}

fn struct_item(o: &Object, enums: &Enums) -> Item {
    let name = ident(&naming::type_name(&o.name));
    let wire: Vec<String> = o.fields.iter().map(|f| f.name.clone()).collect();
    let mut rust_names = unique_names(&wire, naming::field_name);
    let extra = if o.open {
        // The flattened map takes a name no field uses.
        let all = [wire.clone(), vec!["extra".to_string()]].concat();
        let names = unique_names(&all, naming::field_name);
        rust_names = names[..wire.len()].to_vec();
        Some(ident(&names[wire.len()]))
    } else {
        None
    };
    let fields = o
        .fields
        .iter()
        .zip(&rust_names)
        .map(|(f, rust)| field_tokens(o, f, rust, enums));
    let extra_field = extra.map(|e| {
        quote! {
            /// Fields this type does not name, kept so they survive a round trip.
            #[serde(flatten)]
            pub #e: ::serde_json::Map<::std::string::String, ::serde_json::Value>,
        }
    });
    let closed = (!o.open).then(|| quote! { #[serde(deny_unknown_fields)] });
    let docs = o.description.as_deref().map(doc_attrs).unwrap_or_default();
    parse_quote! {
        #(#docs)*
        #[derive(Debug, Clone, PartialEq, ::serde::Serialize, ::serde::Deserialize)]
        #closed
        pub struct #name {
            #(#fields)*
            #extra_field
        }
    }
}

fn field_tokens(o: &Object, f: &Field, rust: &str, enums: &Enums) -> TokenStream {
    let name = ident(rust);
    let mut docs = f.description.clone().unwrap_or_default();
    match &f.value {
        Value::Const { value } => append(&mut docs, &format!("Always `{value}`.")),
        Value::MessageRef { id, version, .. } => {
            append(
                &mut docs,
                &format!("Always `{{\"id\": \"{id}\", \"version\": \"{version}\"}}`."),
            );
        }
        _ => {}
    }
    let docs = if docs.is_empty() {
        Vec::new()
    } else {
        doc_attrs(&docs)
    };
    let rename = (rust.trim_start_matches("r#") != f.name).then(|| {
        let wire = LitStr::new(&f.name, Span::call_site());
        quote! { #[serde(rename = #wire)] }
    });
    let ty = rust_type(o, f, &f.value, enums);
    if f.required {
        quote! {
            #(#docs)*
            #rename
            pub #name: #ty,
        }
    } else {
        let present =
            keeps_present_null(f).then(|| quote! { deserialize_with = "deserialize_present", });

        quote! {
            #(#docs)*
            #rename
            #[serde(default, #present skip_serializing_if = "::core::option::Option::is_none")]
            pub #name: ::core::option::Option<#ty>,
        }
    }
}

fn append(docs: &mut String, line: &str) {
    if !docs.is_empty() {
        docs.push_str("\n\n");
    }
    docs.push_str(line);
}

fn rust_type(o: &Object, f: &Field, v: &Value, enums: &Enums) -> TokenStream {
    match v {
        Value::String(_) => quote! { ::std::string::String },
        Value::Integer { .. } => quote! { i64 },
        Value::Boolean => quote! { bool },
        Value::Any => quote! { ::serde_json::Value },
        Value::JsonObject { .. } => {
            quote! { ::serde_json::Map<::std::string::String, ::serde_json::Value> }
        }
        Value::Const { value } => match value {
            serde_json::Value::String(_) => quote! { ::std::string::String },
            serde_json::Value::Bool(_) => quote! { bool },
            serde_json::Value::Number(_) => quote! { i64 },
            _ => quote! { ::serde_json::Value },
        },
        Value::StringEnum { type_name, .. } => {
            let name = type_name.as_ref().map_or_else(
                || naming::type_name(&format!("{}_{}", o.name, f.name)),
                |t| naming::type_name(t),
            );
            debug_assert!(enums.contains_key(&name));
            let name = ident(&name);
            quote! { #name }
        }
        Value::MessageRef { object, .. } | Value::Object { name: object, .. } => {
            let name = ident(&naming::type_name(object));
            quote! { #name }
        }
        Value::List { item, .. } => {
            let item = rust_type(o, f, item, enums);
            quote! { ::std::vec::Vec<#item> }
        }
    }
}

/// An optional field that may hold any JSON value, `null` included: Parley's schema leaves it
/// unconstrained, so a present `null` is data and must survive a round trip.
fn keeps_present_null(f: &Field) -> bool {
    !f.required && matches!(f.value, Value::Any)
}

"""Parley's message types in Python, rendered from the wesley-parley model.

The model is what ``wesley-parley model`` prints: Parley's vocabulary, interpreted once by the Rust
crate. This module reads it and builds a module through wesley-python's syntax API, mirroring the
TypeScript renderer (``crates/wesley-parley/src/typescript.rs``):

- A GraphQL enum is an alias of a ``Literal`` union; an inline ``@parley_enum`` is an inline one.
- Every object that is not a message's own object is a ``TypedDict``, including the object a
  ``messageRef`` points at, since an ordinary field may reference it too.
- Each message's ``_schema`` is a per-message ``TypedDict``, ``<Object>SchemaRef``, whose ``id`` and
  ``version`` are the message's literal identity. It is defined just before the message.
- Each message is a ``TypedDict``; an optional field is an optional key (absent when unset, never
  ``None``), and ``event`` and every other constant field is a ``Literal``.
- ``Line`` is the union of every message, told apart by ``event``.

wesley-python builds the ``ast`` tree and ``ast.unparse`` prints it, so no source text is assembled
here, and the output imports on Python 3.9 with the standard library only.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING

from wesley_python.syntax import AliasDef, Definition, Field, Module, TypedDictDef, render
from wesley_python.types import (
    AnyValue,
    Bool,
    DictOf,
    Float,
    Int,
    ListOf,
    Literal,
    Ref,
    Str,
    TypeExpr,
    UnionOf,
)

if TYPE_CHECKING:
    from collections.abc import Mapping, Sequence

__all__ = ["ModelError", "module_from_model", "render_model"]

MODULE_DOC = "Parley's message types, generated by wesley-parley from Parley's SDL. Do not edit."
LINE_DOC = "Any Parley message, told apart by `event`."
LINE = "Line"

Json = dict[str, object]


class ModelError(ValueError):
    """The model is not the shape ``wesley-parley model`` prints, or cannot be rendered as Python."""


def _mapping(value: object, where: str) -> Json:
    if not isinstance(value, dict) or not all(isinstance(key, str) for key in value):
        msg = f"{where} must be a JSON object"
        raise ModelError(msg)
    return value


def _member(container: Json, key: str, where: str) -> object:
    if key not in container:
        msg = f"{where} has no {key!r}"
        raise ModelError(msg)
    return container[key]


def _string(container: Json, key: str, where: str) -> str:
    value = _member(container, key, where)
    if not isinstance(value, str):
        msg = f"{where}: {key!r} must be a string"
        raise ModelError(msg)
    return value


def _optional_string(container: Json, key: str, where: str) -> str | None:
    if key not in container:
        return None
    return _string(container, key, where)


def _boolean(container: Json, key: str, where: str) -> bool:
    value = _member(container, key, where)
    if not isinstance(value, bool):
        msg = f"{where}: {key!r} must be a boolean"
        raise ModelError(msg)
    return value


def _array(container: Json, key: str, where: str) -> list[object]:
    value = _member(container, key, where)
    if not isinstance(value, list):
        msg = f"{where}: {key!r} must be an array"
        raise ModelError(msg)
    return value


@dataclass(frozen=True)
class _Message:
    id: str
    version: str
    object: str


@dataclass(frozen=True)
class _Field:
    name: str
    description: str | None
    required: bool
    value: Json


@dataclass(frozen=True)
class _Object:
    name: str
    description: str | None
    fields: tuple[_Field, ...]


@dataclass(frozen=True)
class _SchemaRef:
    """A ``messageRef`` value: the referenced object and the pinned identity."""

    object: str
    id: str
    version: str


def _read_message(value: object, where: str) -> _Message:
    message = _mapping(value, where)
    return _Message(
        id=_string(message, "id", where),
        version=_string(message, "version", where),
        object=_string(message, "object", where),
    )


def _read_object(key: str, value: object) -> _Object:
    where = f"object {key}"
    obj = _mapping(value, where)
    name = _string(obj, "name", where)
    if name != key:
        msg = f"{where} is named {name!r}"
        raise ModelError(msg)
    fields: list[_Field] = []
    for index, item in enumerate(_array(obj, "fields", where)):
        field = _mapping(item, f"{where}, field {index}")
        field_name = _string(field, "name", f"{where}, field {index}")
        field_where = f"{where}, field {field_name}"
        fields.append(
            _Field(
                name=field_name,
                description=_optional_string(field, "description", field_where),
                required=_boolean(field, "required", field_where),
                value=_mapping(_member(field, "value", field_where), f"{field_where}: the value"),
            )
        )
    return _Object(name=name, description=_optional_string(obj, "description", where), fields=tuple(fields))


def _kind(value: Json, where: str) -> str:
    return _string(value, "kind", where)


def _list_item(value: Json, where: str) -> Json:
    return _mapping(_member(value, "item", where), f"{where}: the list item")


def _schema_ref(value: Json, where: str) -> _SchemaRef:
    return _SchemaRef(
        object=_string(value, "object", where),
        id=_string(value, "id", where),
        version=_string(value, "version", where),
    )


def _schema_ref_name(message_object: str) -> str:
    return message_object + "SchemaRef"


def _string_values(value: Json, where: str) -> list[str]:
    values = _array(value, "values", where)
    if not values or not all(isinstance(item, str) for item in values):
        msg = f"{where}: 'values' must be a non-empty array of strings"
        raise ModelError(msg)
    return [item for item in values if isinstance(item, str)]


def _literal_union(values: Sequence[str]) -> UnionOf:
    return UnionOf(*[Literal(item) for item in values])


def _const_type(literal: object) -> TypeExpr:
    """Type a constant: a ``Literal`` for a string, boolean or integer, as TypeScript has it."""
    if isinstance(literal, (str, bool, int)):
        return Literal(literal)
    if isinstance(literal, float):
        return Float()
    return AnyValue()


class _Renderer:
    """Converts the model's values to type expressions, checking what each one references."""

    def __init__(self, objects: Mapping[str, _Object]) -> None:
        self.objects = objects

    def type_of(self, value: Json, where: str, message_object: str | None) -> TypeExpr:  # noqa: C901, PLR0911 - one branch per kind
        """Build the type expression for ``value``; a ``messageRef`` is allowed only in a message's object."""
        kind = _kind(value, where)
        if kind == "string":
            return Str()
        if kind == "integer":
            return Int()
        if kind == "boolean":
            return Bool()
        if kind == "any":
            return AnyValue()
        if kind == "jsonObject":
            return DictOf(AnyValue())
        if kind == "const":
            return _const_type(_member(value, "value", where))
        if kind == "stringEnum":
            type_name = _optional_string(value, "typeName", where)
            values = _string_values(value, where)
            return _literal_union(values) if type_name is None else Ref(type_name)
        if kind == "messageRef":
            ref = _schema_ref(value, where)
            if message_object is None:
                msg = f"{where}: a messageRef is allowed only as a field of a message's object"
                raise ModelError(msg)
            self.require_object(ref.object, where)
            return Ref(_schema_ref_name(message_object))
        if kind == "object":
            name = _string(value, "name", where)
            self.require_object(name, where)
            return Ref(name)
        if kind == "list":
            return ListOf(self.type_of(_list_item(value, where), where, None))
        msg = f"{where}: unknown value kind {kind!r}"
        raise ModelError(msg)

    def require_object(self, name: str, where: str) -> None:
        """Refuse a reference to an object the model does not define."""
        if name not in self.objects:
            msg = f"{where}: references object {name!r}, which the model does not define"
            raise ModelError(msg)

    def typed_dict(self, obj: _Object, doc: str | None, *, message: bool) -> TypedDictDef:
        """Build the ``TypedDict`` for ``obj``; field descriptions become field docs."""
        fields = [
            Field(
                field.name,
                self.type_of(field.value, f"object {obj.name}, field {field.name}", obj.name if message else None),
                required=field.required,
                doc=field.description,
            )
            for field in obj.fields
        ]
        return TypedDictDef(obj.name, fields, doc=doc)

    def schema_ref_def(self, message: _Message, obj: _Object) -> TypedDictDef | None:
        """Build the ``<Object>SchemaRef`` of a message, pinned to its identity; ``None`` without a ``_schema``."""
        refs = [
            _schema_ref(field.value, f"object {obj.name}, field {field.name}")
            for field in obj.fields
            if _kind(field.value, f"object {obj.name}, field {field.name}") == "messageRef"
        ]
        if not refs:
            return None
        if any(ref != refs[0] for ref in refs):
            msg = f"object {obj.name}: its messageRef fields disagree"
            raise ModelError(msg)
        ref = refs[0]
        if (ref.id, ref.version) != (message.id, message.version):
            msg = (
                f"object {obj.name}: its messageRef pins {ref.id} {ref.version}, "
                f"but the message is {message.id} {message.version}"
            )
            raise ModelError(msg)
        self.require_object(ref.object, f"object {obj.name}")
        docs = {field.name: field.description for field in self.objects[ref.object].fields}
        return TypedDictDef(
            _schema_ref_name(obj.name),
            [
                Field("id", Literal(ref.id), required=True, doc=docs.get("id")),
                Field("version", Literal(ref.version), required=True, doc=docs.get("version")),
            ],
        )


def _collect_enums(value: Json, where: str, out: dict[str, list[str]]) -> None:
    kind = _kind(value, where)
    if kind == "stringEnum":
        type_name = _optional_string(value, "typeName", where)
        if type_name is not None:
            values = _string_values(value, where)
            if out.setdefault(type_name, values) != values:
                msg = f"{where}: enum {type_name} is declared with different values elsewhere"
                raise ModelError(msg)
    elif kind == "list":
        _collect_enums(_list_item(value, where), where, out)


def _message_doc(message: _Message, obj: _Object) -> str:
    identity = f"Message `{message.id}`, schema version `{message.version}`."
    return identity if not obj.description else f"{obj.description}\n\n{identity}"


def _definitions(messages: Sequence[_Message], objects: Mapping[str, _Object]) -> list[Definition]:
    renderer = _Renderer(objects)
    for message in messages:
        renderer.require_object(message.object, f"message {message.id}")
    message_objects = {message.object for message in messages}

    enums: dict[str, list[str]] = {}
    for obj in objects.values():
        for field in obj.fields:
            _collect_enums(field.value, f"object {obj.name}, field {field.name}", enums)

    definitions: list[Definition] = [AliasDef(name, _literal_union(enums[name])) for name in sorted(enums)]
    definitions.extend(
        renderer.typed_dict(obj, None, message=False) for obj in objects.values() if obj.name not in message_objects
    )
    for message in messages:
        obj = objects[message.object]
        schema_ref = renderer.schema_ref_def(message, obj)
        if schema_ref is not None:
            definitions.append(schema_ref)
        definitions.append(renderer.typed_dict(obj, _message_doc(message, obj), message=True))
    if not messages:
        msg = "the model declares no messages"
        raise ModelError(msg)
    line = UnionOf(*[Ref(message.object) for message in messages])
    definitions.append(AliasDef(LINE, line, doc=LINE_DOC))
    return definitions


def module_from_model(model: object) -> Module:
    """Build the module of message types for ``model``.

    Raises :class:`ModelError` when the model is malformed or names something Python cannot bind.
    """
    root = _mapping(model, "the model")
    messages = [
        _read_message(item, f"messages[{index}]") for index, item in enumerate(_array(root, "messages", "the model"))
    ]
    objects_json = _mapping(_member(root, "objects", "the model"), "the model's objects")
    objects = {key: _read_object(key, value) for key, value in objects_json.items()}
    try:
        return Module(_definitions(messages, objects), doc=MODULE_DOC)
    except ModelError:
        raise
    except (ValueError, TypeError) as error:
        raise ModelError(str(error)) from error


def render_model(model: object) -> str:
    """Render the module of message types for ``model`` as Python source, ending in one newline.

    Raises :class:`ModelError` as :func:`module_from_model` does, and when two definitions would
    bind the same name.
    """
    module = module_from_model(model)
    try:
        return render(module)
    except ValueError as error:
        raise ModelError(str(error)) from error

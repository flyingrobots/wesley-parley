"""The model rendered as Python: the golden, the mapping of each kind, and malformed models."""

from __future__ import annotations

import copy
import unittest
from typing import cast

from wesley_python.syntax import AliasDef, Field, Module, TypedDictDef
from wesley_python.types import AnyValue, Bool, DictOf, Float, Int, ListOf, Literal, Ref, Str, UnionOf

from tests.support import assert_golden, load_model
from wesley_parley.render import ModelError, module_from_model, render_model

MODULE_DOC = "Parley's message types, generated by wesley-parley from Parley's SDL. Do not edit."
LINE_DOC = "Any Parley message, told apart by `event`."

Json = dict[str, object]


def _field(name: str, value: Json, *, required: bool = True, description: str | None = None) -> Json:
    field: Json = {"name": name, "required": required, "value": value}
    if description is not None:
        field["description"] = description
    return field


def _object(name: str, *fields: Json, description: str | None = None) -> Json:
    obj: Json = {"name": name, "open": True, "fields": list(fields), "rules": {}}
    if description is not None:
        obj["description"] = description
    return obj


def _message(obj: str, message_id: str, version: str = "1.0.0") -> Json:
    return {"id": message_id, "version": version, "title": message_id.replace(".", " "), "object": obj}


def _schema_ref(message_id: str, version: str = "1.0.0") -> Json:
    return {"kind": "messageRef", "object": "SchemaRef", "id": message_id, "version": version}


SCHEMA_REF_OBJECT = _object(
    "SchemaRef",
    _field("id", {"kind": "string"}, description="The message id."),
    _field("version", {"kind": "string"}, description="The schema version."),
)

# The object a messageRef points at is still an ordinary TypedDict: another field may reference it.
SCHEMA_REF_DEF = TypedDictDef(
    "SchemaRef",
    [
        Field("id", Str(), required=True, doc="The message id."),
        Field("version", Str(), required=True, doc="The schema version."),
    ],
)


def _model(messages: list[Json], *objects: Json) -> Json:
    return {"messages": messages, "objects": {obj["name"]: obj for obj in objects}}


def _objects(model: Json) -> dict[str, Json]:
    return cast("dict[str, Json]", model["objects"])


def _ping_model(*fields: Json, description: str | None = None) -> Json:
    """One message, ``Ping`` (``x.ping``), with an ``event`` and the given fields, and its ``_schema``."""
    ping = _object(
        "Ping",
        _field("event", {"kind": "const", "value": "ping"}),
        *fields,
        _field("_schema", _schema_ref("x.ping")),
        description=description,
    )
    return _model([_message("Ping", "x.ping")], ping, SCHEMA_REF_OBJECT)


def _ping_schema_ref() -> TypedDictDef:
    return TypedDictDef(
        "PingSchemaRef",
        [
            Field("id", Literal("x.ping"), required=True, doc="The message id."),
            Field("version", Literal("1.0.0"), required=True, doc="The schema version."),
        ],
    )


def _ping(*fields: Field, doc: str = "Message `x.ping`, schema version `1.0.0`.") -> TypedDictDef:
    return TypedDictDef(
        "Ping",
        [
            Field("event", Literal("ping"), required=True),
            *fields,
            Field("_schema", Ref("PingSchemaRef"), required=True),
        ],
        doc=doc,
    )


def _ping_module(*fields: Field, enums: tuple[AliasDef, ...] = (), objects: tuple[TypedDictDef, ...] = ()) -> Module:
    return Module(
        [
            *enums,
            SCHEMA_REF_DEF,
            *objects,
            _ping_schema_ref(),
            _ping(*fields),
            AliasDef("Line", UnionOf(Ref("Ping")), doc=LINE_DOC),
        ],
        doc=MODULE_DOC,
    )


class GoldenTest(unittest.TestCase):
    def test_parley_model_matches_golden(self) -> None:
        assert_golden(self, "messages.py", render_model(load_model()))

    def test_rendering_is_deterministic(self) -> None:
        self.assertEqual(render_model(load_model()), render_model(load_model()))

    def test_every_message_is_in_line(self) -> None:
        model = load_model()
        line = cast("AliasDef", module_from_model(model).definitions[-1])
        self.assertEqual(line.name, "Line")
        self.assertEqual(len(cast("UnionOf", line.type).members), 17)


class MappingTest(unittest.TestCase):
    def test_a_message_with_its_schema_ref(self) -> None:
        self.assertEqual(module_from_model(_ping_model()), _ping_module())

    def test_scalars(self) -> None:
        model = _ping_model(
            _field("s", {"kind": "string", "minLength": 1}),
            _field("i", {"kind": "integer", "bits": 64, "constraints": {"minimum": 0}}),
            _field("b", {"kind": "boolean"}),
            _field("a", {"kind": "any"}),
            _field("j", {"kind": "jsonObject", "minProperties": 1}),
        )
        expected = _ping_module(
            Field("s", Str(), required=True),
            Field("i", Int(), required=True),
            Field("b", Bool(), required=True),
            Field("a", AnyValue(), required=True),
            Field("j", DictOf(AnyValue()), required=True),
        )
        self.assertEqual(module_from_model(model), expected)

    def test_consts(self) -> None:
        model = _ping_model(
            _field("zero", {"kind": "const", "value": 0}),
            _field("yes", {"kind": "const", "value": True}),
            _field("half", {"kind": "const", "value": 0.5}),
            _field("nothing", {"kind": "const", "value": None}),
        )
        expected = _ping_module(
            Field("zero", Literal(0), required=True),
            Field("yes", Literal(value=True), required=True),
            Field("half", Float(), required=True),
            Field("nothing", AnyValue(), required=True),
        )
        self.assertEqual(module_from_model(model), expected)

    def test_optional_fields_and_descriptions(self) -> None:
        model = _ping_model(
            _field("from", {"kind": "integer", "bits": 32, "constraints": {}}, required=False, description="First."),
        )
        expected = _ping_module(Field("from", Int(), required=False, doc="First."))
        self.assertEqual(module_from_model(model), expected)

    def test_message_description_precedes_its_identity(self) -> None:
        model = _ping_model(description="A ping.")
        module = module_from_model(model)
        ping = cast("TypedDictDef", module.definitions[2])
        self.assertEqual(ping.doc, "A ping.\n\nMessage `x.ping`, schema version `1.0.0`.")

    def test_enums_named_and_inline(self) -> None:
        model = _ping_model(
            _field("op", {"kind": "stringEnum", "values": ["b", "a"], "typeName": "Op"}),
            _field("ops", {"kind": "list", "item": {"kind": "stringEnum", "values": ["z"], "typeName": "Alpha"}}),
            _field("mode", {"kind": "stringEnum", "values": ["on", "off"]}),
        )
        expected = _ping_module(
            Field("op", Ref("Op"), required=True),
            Field("ops", ListOf(Ref("Alpha")), required=True),
            Field("mode", UnionOf(Literal("on"), Literal("off")), required=True),
            enums=(
                AliasDef("Alpha", UnionOf(Literal("z"))),
                AliasDef("Op", UnionOf(Literal("b"), Literal("a"))),
            ),
        )
        self.assertEqual(module_from_model(model), expected)

    def test_nested_objects_and_lists(self) -> None:
        window = _object("Window", _field("from", {"kind": "integer", "bits": 32, "constraints": {}}))
        model = _ping_model(
            _field("window", {"kind": "object", "name": "Window"}),
            _field("windows", {"kind": "list", "item": {"kind": "object", "name": "Window"}, "minItems": 1}),
        )
        _objects(model)["Window"] = window
        expected = _ping_module(
            Field("window", Ref("Window"), required=True),
            Field("windows", ListOf(Ref("Window")), required=True),
            objects=(TypedDictDef("Window", [Field("from", Int(), required=True)]),),
        )
        self.assertEqual(module_from_model(model), expected)

    def test_an_ordinary_field_may_reference_the_schema_ref_object(self) -> None:
        model = _ping_model(_field("previous", {"kind": "object", "name": "SchemaRef"}))
        expected = _ping_module(Field("previous", Ref("SchemaRef"), required=True))
        self.assertEqual(module_from_model(model), expected)

    def test_line_is_the_union_of_messages_in_order(self) -> None:
        pong = _object(
            "Pong",
            _field("event", {"kind": "const", "value": "pong"}),
            _field("_schema", _schema_ref("x.pong", "2.0.0")),
        )
        model = _ping_model()
        cast("list[Json]", model["messages"]).append(_message("Pong", "x.pong", "2.0.0"))
        _objects(model)["Pong"] = pong
        module = module_from_model(model)
        names = [definition.name for definition in module.definitions]
        self.assertEqual(names, ["SchemaRef", "PingSchemaRef", "Ping", "PongSchemaRef", "Pong", "Line"])
        self.assertEqual(module.definitions[-1], AliasDef("Line", UnionOf(Ref("Ping"), Ref("Pong")), doc=LINE_DOC))


class MalformedModelTest(unittest.TestCase):
    def _assert_refused(self, model: object, *needles: str) -> None:
        with self.assertRaises(ModelError) as caught:
            module_from_model(model)
        for needle in needles:
            self.assertIn(needle, str(caught.exception))

    def test_not_an_object(self) -> None:
        self._assert_refused([], "model")

    def test_missing_messages(self) -> None:
        self._assert_refused({"objects": {}}, "messages")

    def test_unknown_kind(self) -> None:
        self._assert_refused(_ping_model(_field("x", {"kind": "float"})), "Ping", "x", "float")

    def test_message_object_missing(self) -> None:
        model = _ping_model()
        del _objects(model)["Ping"]
        self._assert_refused(model, "Ping")

    def test_field_without_required(self) -> None:
        model = _ping_model()
        broken = copy.deepcopy(model)
        fields = cast("list[Json]", _objects(broken)["Ping"]["fields"])
        fields[0].pop("required")
        self._assert_refused(broken, "Ping", "event", "required")

    def test_name_that_is_not_an_identifier(self) -> None:
        self._assert_refused(
            _ping_model(_field("x", {"kind": "stringEnum", "values": ["a"], "typeName": "not-a-name"})),
            "not-a-name",
        )


if __name__ == "__main__":
    unittest.main()
